// Generate a list of triangle vertices (2 floats per vertex) in NDC for the
// given text string.  pixelX / pixelY are the top-left position in screen
// pixels.  scale multiplies the base 5×7 glyph size.  screenW / screenH are
// the window dimensions used to convert pixel coords → NDC.
//
// Returns the number of vertices written (each vertex is 2 floats: x,y).
inline int generateTextVertices(float pixelX, float pixelY,
                                const char* text, float scale,
                                int screenW, int screenH,
                                std::vector<float>& outVerts)
{
    outVerts.clear();
    const float glyphW = 6.0f * scale;   // 5 pixels + 1 spacing
    const float glyphH = 9.0f * scale;   // 7 pixels + 2 spacing
    const float pixW   = scale;

    float cursorX = pixelX;
    float cursorY = pixelY;

    auto px2ndcX = [&](float px) { return (px / screenW) *  2.0f - 1.0f; };
    auto px2ndcY = [&](float py) { return (1.0f - py / screenH) * 2.0f - 1.0f; };

    int vertCount = 0;
    for (const char* p = text; *p; ++p) {
        if (*p == '\n') { cursorX = pixelX; cursorY += glyphH; continue; }
        int idx = *p - 32;
        if (idx < 0 || idx > 94) { cursorX += glyphW; continue; }

        const unsigned char* g = glyphs[idx];
        for (int row = 0; row < 7; ++row) {
            for (int col = 0; col < 5; ++col) {
                if (g[row] & (0x10 >> col)) {
                    float x0 = cursorX + col * pixW;
                    float y0 = cursorY + row * pixW;
                    float x1 = x0 + pixW;
                    float y1 = y0 + pixW;

                    float nx0 = px2ndcX(x0), nx1 = px2ndcX(x1);
                    float ny0 = px2ndcY(y0), ny1 = px2ndcY(y1);

                    // Two triangles per pixel
                    outVerts.push_back(nx0); outVerts.push_back(ny0);
                    outVerts.push_back(nx1); outVerts.push_back(ny0);
                    outVerts.push_back(nx0); outVerts.push_back(ny1);

                    outVerts.push_back(nx1); outVerts.push_back(ny0);
                    outVerts.push_back(nx1); outVerts.push_back(ny1);
                    outVerts.push_back(nx0); outVerts.push_back(ny1);

                    vertCount += 6;
                }
            }
        }
        cursorX += glyphW;
    }
    return vertCount;
}

